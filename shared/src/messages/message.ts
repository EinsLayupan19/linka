import { z } from 'zod';

export const MESSAGE_MAX_LENGTH = 4000;
export const MESSAGE_PAGE_DEFAULT_LIMIT = 50;
export const MESSAGE_PAGE_MAX_LIMIT = 100;

/** Only text for now; new kinds (e.g. attachment-only, system notices) are added here. */
export const MESSAGE_TYPES = ['text'] as const;
export const messageTypeSchema = z.enum(MESSAGE_TYPES);
export type MessageType = z.infer<typeof messageTypeSchema>;

/**
 * Message text is stored exactly as typed (leading spaces, line breaks and all);
 * it only has to contain something besides whitespace.
 */
export const messageContentSchema = z
  .string()
  .max(MESSAGE_MAX_LENGTH, `Messages can be at most ${MESSAGE_MAX_LENGTH} characters.`)
  .refine((value) => value.trim().length > 0, 'Write a message.');

/**
 * Body of POST /api/conversations/:conversationId/messages.
 * The sender is always the signed-in user, so it never appears here.
 * `clientId` is generated by the sending client: sending again with the same clientId
 * (a retry) returns the original message instead of creating a duplicate.
 */
export const createMessageSchema = z.strictObject({
  content: messageContentSchema,
  clientId: z.uuid('Invalid client id.'),
});

export type CreateMessageInput = z.infer<typeof createMessageSchema>;

export const messageSchema = z.object({
  id: z.uuid(),
  conversationId: z.uuid(),
  /** null when the sender's account was deleted. */
  senderId: z.uuid().nullable(),
  /** The sender's idempotency key, so a client can match its pending message. */
  clientId: z.uuid().nullable(),
  type: messageTypeSchema,
  content: z.string().nullable(),
  /** Millisecond precision, always UTC ("...T12:00:00.000Z"). */
  createdAt: z.iso.datetime(),
  editedAt: z.iso.datetime().nullable(),
  deletedAt: z.iso.datetime().nullable(),
});

export type Message = z.infer<typeof messageSchema>;

/**
 * Query of GET /api/conversations/:conversationId/messages.
 * Without `before`, returns the newest page; with it, the page of messages just older
 * than the cursor. The cursor is opaque: use `nextCursor` from the previous page.
 */
export const messagePageQuerySchema = z.object({
  limit: z.coerce
    .number('Limit must be a number.')
    .int('Limit must be a whole number.')
    .min(1, 'Limit must be at least 1.')
    .max(MESSAGE_PAGE_MAX_LIMIT, `Limit can be at most ${MESSAGE_PAGE_MAX_LIMIT}.`)
    .default(MESSAGE_PAGE_DEFAULT_LIMIT),
  before: z.string().min(1).max(200).optional(),
});

export type MessagePageQuery = z.infer<typeof messagePageQuerySchema>;

export const messagePageSchema = z.object({
  /** Oldest first, so the page can be shown top to bottom as-is. */
  messages: z.array(messageSchema),
  /** Pass as `before` to load older messages; null when there are none. */
  nextCursor: z.string().nullable(),
});

export type MessagePage = z.infer<typeof messagePageSchema>;

/** Messages are ordered by (createdAt, id); the id breaks ties between identical timestamps. */
export function compareMessages(a: Pick<Message, 'createdAt' | 'id'>, b: Pick<Message, 'createdAt' | 'id'>): number {
  if (a.createdAt !== b.createdAt) return a.createdAt < b.createdAt ? -1 : 1;
  if (a.id === b.id) return 0;
  return a.id < b.id ? -1 : 1;
}
